from __future__ import annotations

import subprocess
import tempfile
from collections.abc import Callable
from pathlib import Path

from labelmeme import media
from labelmeme.schema import WireBox, WireRun, WireTemplate, write_template

WIDTH, HEIGHT, FPS, FRAME_COUNT, CUT = 640, 360, 24, 48, 24

SOURCE_MD = """# fixture

Synthetic test clip, not real footage. Generated by `uv run python -m labelmeme fixture`
from ffmpeg's `testsrc2` pattern (2 s, 24 fps, 640x360) with a silent AAC track.
Subjects and boxes are hand-written in `pipeline/labelmeme/fixture.py`.
"""


def _alice_box(f: int) -> WireBox:
    x = 20 + round(f * 480 / (FRAME_COUNT - 1))
    y = 2 if f < 8 else min(120, 2 + (f - 8) * 8)
    return [x, y, 120, 200]


def _bob_box(f: int) -> WireBox:
    return [500 - (f - 4) * 10, 160, 100, 160]


def _run(start: int, end: int, box: Callable[[int], WireBox]) -> WireRun:
    return {"from": start, "boxes": [box(f) for f in range(start, end)]}


def fixture_template() -> WireTemplate:
    return {
        "version": 1,
        "id": "fixture",
        "title": "Fixture: test pattern",
        "credit": "Synthetic ffmpeg testsrc2 pattern, no rights reserved",
        "width": WIDTH,
        "height": HEIGHT,
        "fps": FPS,
        "frameCount": FRAME_COUNT,
        "cuts": [CUT],
        "subjects": [
            {"id": "alice", "name": "Alice", "runs": [_run(0, CUT, _alice_box), _run(CUT, FRAME_COUNT, _alice_box)]},
            {"id": "bob", "name": "Bob", "runs": [_run(4, 20, _bob_box), _run(28, 36, _bob_box)]},
        ],
    }


def make_fixture(templates_dir: Path) -> Path:
    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp)
        src, video, thumb = work / "src.mkv", work / "video.mp4", work / "thumb.jpg"
        subprocess.run(
            [
                "ffmpeg", "-v", "error", "-y", "-f", "lavfi",
                "-i", f"testsrc2=size={WIDTH}x{HEIGHT}:rate={FPS}:duration={FRAME_COUNT / FPS}",
                "-c:v", "ffv1", str(src),
            ],
            check=True, start_new_session=True,
        )
        info = media.encode(src, video, FPS)
        frames = media.count_frames_cv2(video)
        if (info.width, info.height, frames) != (WIDTH, HEIGHT, FRAME_COUNT):
            raise ValueError(f"fixture video is {info.width}x{info.height} with {frames} frames")
        media.thumbnail(video, thumb)
        return write_template(templates_dir, fixture_template(), video, thumb, SOURCE_MD)
