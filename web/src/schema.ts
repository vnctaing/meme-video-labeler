/** Box at one frame: integer pixels in template coordinates, top-left origin, w and h >= 1, fully inside the frame. */
export type WireBox = [x: number, y: number, w: number, h: number];

/** A stretch of consecutive frames where a subject is visible. */
export interface WireRun {
  /** First frame of the run. */
  from: number;
  /** `boxes[i]` is the box at frame `from + i`; the run ends (exclusive) at `from + boxes.length`. */
  boxes: WireBox[];
}

/** A person or thing the user can label. */
export interface WireSubject {
  /** Slug matching `[a-z0-9-]+`, unique within the template. */
  id: string;
  /** Display name shown next to the label input. */
  name: string;
  /** Sorted by `from`, non-overlapping, each inside [0, frameCount), none crossing a cut. */
  runs: WireRun[];
}

/** Contents of `templates/<id>/template.json`. */
export interface WireTemplate {
  /** Schema version, always 1. */
  version: 1;
  /** Directory name under `templates/`. */
  id: string;
  /** Title shown in the gallery and editor. */
  title: string;
  /** Attribution line the gallery and editor show. */
  credit: string;
  /** Frame width in pixels. */
  width: number;
  /** Frame height in pixels. */
  height: number;
  /** Integer frames per second; video.mp4 is constant frame rate at this value with no B-frames and no edit list. */
  fps: number;
  /** Number of frames in video.mp4, measured by decoding it. */
  frameCount: number;
  /** Frames where a new shot starts: sorted, unique, each in (0, frameCount). */
  cuts: number[];
  /** People and things that can be labelled. */
  subjects: WireSubject[];
}

/** One gallery entry of `templates/index.json`. */
export interface WireIndexEntry {
  /** Template id. */
  id: string;
  /** Template title. */
  title: string;
  /** Template credit line. */
  credit: string;
  /** Frame width in pixels. */
  width: number;
  /** Frame height in pixels. */
  height: number;
  /** Integer frames per second. */
  fps: number;
  /** Number of frames. */
  frameCount: number;
  /** Number of subjects. */
  subjectCount: number;
}

/** Contents of `templates/index.json`, regenerated by the pipeline from every template directory. */
export interface WireIndex {
  /** Schema version, always 1. */
  version: 1;
  /** Entries sorted by id. */
  templates: WireIndexEntry[];
}
